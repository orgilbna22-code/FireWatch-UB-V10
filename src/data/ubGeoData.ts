export const UB_DISTRICTS: DistrictData[] = RAW_DISTRICTS.map(buildDistrict);

const DISTRICT_BY_ID = new Map(UB_DISTRICTS.map((d) => [d.id, d]));

const CLAMPED_CURATED_KHOROOS: KhorooData[] = UB_KHOROOS_CURATED.map((k) => {
  const parent = DISTRICT_BY_ID.get(k.districtId);
  const safeCenter = parent
    ? clampPointInsidePolygon(k.center[0], k.center[1], parent.polygon, parent.center)
    : k.center;
  return {
    ...k,
    center: safeCenter,
    riskLevel: riskLevelFromScore(k.riskScore),
  };
});

const SYNTHESIZED_KHOROOS: KhorooData[] = synthesizeKhoroos(UB_DISTRICTS, CLAMPED_CURATED_KHOROOS);

export const UB_KHOROOS: KhorooData[] = [...CLAMPED_CURATED_KHOROOS, ...SYNTHESIZED_KHOROOS];

export const TOTAL_KHOROO_COUNT = UB_KHOROOS.length;
export const MODELLED_KHOROO_COUNT = UB_KHOROOS.filter((k) => k.isModelled).length;

const TOTAL_KHOROO_POP = UB_KHOROOS.reduce((s, k) => s + k.population, 0) || 1;
export const CITY_AVERAGE_RISK = Math.round(
  UB_KHOROOS.reduce((s, k) => s + k.riskScore * k.population, 0) / TOTAL_KHOROO_POP
);

export const TOTAL_CITY_POPULATION = UB_DISTRICTS.reduce((s, d) => s + d.population, 0);
export const TOTAL_HISTORICAL_INCIDENTS = UB_DISTRICTS.reduce(
  (s, d) => s + d.historicalIncidentsCount,
  0
);
export const SAMPLE_INCIDENT_COUNT = 12;

export function getKhoroosByDistrict(districtId: string): KhorooData[] {
  return UB_KHOROOS.filter((k) => k.districtId === districtId);
}

