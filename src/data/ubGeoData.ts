type DistrictSeedInput = Omit<DistrictData, 'riskScore' | 'riskLevel' | 'contributions'>;

function buildDistrict(seed: DistrictSeedInput): DistrictData {
  const placeholder: DistrictData = {
    ...seed,
    riskScore: 0,
    riskLevel: 'moderate',
    contributions: [],
  };
  const computed = computeWeightedDistrictRisk(placeholder);
  return {
    ...placeholder,
    riskScore: computed.score,
    riskLevel: computed.level,
    contributions: computed.contributions,
    locationConfidence: seed.locationConfidence ?? 'district_centroid',
  };
}

